"""The skill archive is what users install by hand — it must not ship build junk.

`package_skill.py` allowlists the repo root (SKILL.md, LICENSE, README.md,
scripts/, references/), which is the right instinct. But `scripts/` is also
where setuptools writes `*.egg-info` during a build, and that directory is
inside an allowlisted root: every egg-info generated by a local `wheel` or
`build` run landed in the archive handed to users.
"""

import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import package_skill as ps  # noqa: E402


class TestSkillArchiveContents(unittest.TestCase):
    def test_egg_info_is_never_shipped(self):
        junk = ps.REPO / "scripts" / "hermes_project_oracle.egg-info" / "SOURCES.txt"
        self.assertFalse(ps.should_ship(junk))
        self.assertFalse(ps.should_ship(junk.parent))

    def test_the_code_itself_is_shipped(self):
        for rel in ("SKILL.md", "scripts/oracle_lint.py",
                    "scripts/oracle_scan_lib/detectors.py",
                    "references/interview-script.md"):
            self.assertTrue(ps.should_ship(ps.REPO / rel), rel)

    def test_development_artifacts_are_not_shipped(self):
        for rel in (".github/workflows/ci.yml", "tests/test_oracle.py",
                    "package_skill.py", "ruff.toml", ".coverage"):
            self.assertFalse(ps.should_ship(ps.REPO / rel), rel)


if __name__ == "__main__":
    unittest.main()
